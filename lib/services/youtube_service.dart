import 'dart:convert';
import 'package:youtube_explode_dart/youtube_explode_dart.dart';
import '../models/material_item.dart';
import '../models/segment.dart';

class YouTubeImportResult {
  final String videoId;
  final String title;
  final List<Segment> segments;
  final String selectedLanguage;

  const YouTubeImportResult({
    required this.videoId,
    required this.title,
    required this.segments,
    required this.selectedLanguage,
  });
}

class YouTubeService {
  final YoutubeExplode _yt = YoutubeExplode();

  /// Extract video ID from diverse URL formats or bare IDs
  static String? extractVideoId(String input) {
    final trimmed = input.trim();
    if (trimmed.isEmpty) return null;

    // Bare 11-char ID
    final idRegex = RegExp(r'^[a-zA-Z0-9_-]{11}$');
    if (idRegex.hasMatch(trimmed)) {
      return trimmed;
    }

    final uri = Uri.tryParse(trimmed);
    if (uri == null) return null;

    // youtu.be/<id>
    if (uri.host.contains('youtu.be')) {
      final segments = uri.pathSegments;
      if (segments.isNotEmpty && segments[0].length == 11) {
        return segments[0];
      }
    }

    // youtube.com/watch?v=<id>
    if (uri.queryParameters.containsKey('v')) {
      final v = uri.queryParameters['v'];
      if (v != null && v.length == 11) {
        return v;
      }
    }

    // youtube.com/embed/<id> or youtube.com/v/<id> or /shorts/<id>
    final pathSegments = uri.pathSegments;
    for (int i = 0; i < pathSegments.length; i++) {
      if (pathSegments[i] == 'embed' ||
          pathSegments[i] == 'v' ||
          pathSegments[i] == 'shorts') {
        if (i + 1 < pathSegments.length && pathSegments[i + 1].length == 11) {
          return pathSegments[i + 1];
        }
      }
    }

    return null;
  }

  /// Fetch video metadata and captions
  Future<YouTubeImportResult> fetchVideoWithCaptions(
    String videoUrlOrId, {
    String? preferredLanguageCode,
  }) async {
    final videoId = extractVideoId(videoUrlOrId);
    if (videoId == null) {
      throw Exception('Invalid YouTube URL or Video ID');
    }

    // 1. Fetch metadata
    final video = await _yt.videos.get(videoId);
    final title = video.title;

    // 2. Fetch caption manifest
    final manifest = await _yt.videos.closedCaptions.getManifest(videoId);
    if (manifest.tracks.isEmpty) {
      throw Exception('No subtitles/closed captions found for this video.');
    }

    // 3. Find optimal track
    // Prioritize:
    // a) Preferred language manual track
    // b) Preferred language auto track
    // c) English manual track
    // d) Any manual track
    // e) Any track
    ClosedCaptionTrackInfo? selectedTrack;

    final lang = preferredLanguageCode?.toLowerCase();

    if (lang != null && lang.isNotEmpty) {
      // Look for preferred manual
      for (final track in manifest.tracks) {
        if (!track.isAutoGenerated &&
            (track.language.code.toLowerCase().startsWith(lang) ||
             track.language.name.toLowerCase().contains(lang))) {
          selectedTrack = track;
          break;
        }
      }

      // Look for preferred auto
      if (selectedTrack == null) {
        for (final track in manifest.tracks) {
          if (track.isAutoGenerated &&
              (track.language.code.toLowerCase().startsWith(lang) ||
               track.language.name.toLowerCase().contains(lang))) {
            selectedTrack = track;
            break;
          }
        }
      }
    }

    // Fallback: look for any manual track
    if (selectedTrack == null) {
      for (final track in manifest.tracks) {
        if (!track.isAutoGenerated) {
          selectedTrack = track;
          break;
        }
      }
    }

    // Fallback: take first available
    selectedTrack ??= manifest.tracks.first;

    // 4. Download and parse captions
    final captionTrack = await _yt.videos.closedCaptions.get(selectedTrack);
    final segments = <Segment>[];

    for (final caption in captionTrack.captions) {
      final cleanText = caption.text.replaceAll('\n', ' ').trim();
      if (cleanText.isNotEmpty) {
        segments.add(
          Segment(
            text: cleanText,
            startMs: caption.offset.inMilliseconds,
            durationMs: caption.duration.inMilliseconds,
          ),
        );
      }
    }

    if (segments.isEmpty) {
      throw Exception('Caption track was empty.');
    }

    return YouTubeImportResult(
      videoId: videoId,
      title: title,
      segments: segments,
      selectedLanguage: selectedTrack.language.name,
    );
  }

  /// Helper to convert result into MaterialItem
  static MaterialItem createMaterial({
    required String title,
    required String videoId,
    required List<Segment> segments,
  }) {
    final segmentsJson = jsonEncode(segments.map((s) => s.toJson()).toList());
    return MaterialItem(
      title: title,
      sourceType: 'youtube',
      youtubeId: videoId,
      segmentsJson: segmentsJson,
      createdAt: DateTime.now().millisecondsSinceEpoch,
    );
  }

  void dispose() {
    _yt.close();
  }
}
